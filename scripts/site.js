document.getElementById('copyButton').onclick = function () {
    const resultDiv = document.getElementById('result');
    const content = resultDiv.textContent || resultDiv.innerText;

    // Create a temporary textarea element
    const tempTextArea = document.createElement('textarea');
    tempTextArea.value = content.replace('Done with: ', '');
    document.body.appendChild(tempTextArea);

    // Select the text and copy it to the clipboard
    tempTextArea.select();
    document.execCommand('copy');

    // Remove the temporary textarea
    document.body.removeChild(tempTextArea);

    // Optional: Give feedback to the user
    //alert('Copied to clipboard');
};
function openTab(evt, tabName) {
    const tabcontents = document.querySelectorAll('.tabcontent');
    tabcontents.forEach(content => content.classList.remove('active'));

    const tablinks = document.querySelectorAll('.tablinks');
    tablinks.forEach(link => link.classList.remove('active'));

    document.getElementById(tabName).classList.add('active');
    evt.currentTarget.classList.add('active');
}

document.querySelectorAll('.tablinks').forEach(function (tab) {
    tab.addEventListener('click', function (event) {
        openTab(event, tab.getAttribute('data-tab'));
    });

    tab.addEventListener('touchstart', function (event) {
        openTab(event, tab.getAttribute('data-tab'));
    });
});
